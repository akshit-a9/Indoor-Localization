"""Generates the location table and floor maps that the ESP32 firmware embeds.

Writes, into esp32_collector/:
    locations.h   every location the phone recorded: label, phone file, floor, map pixel
    floor_maps.h  map_0.png / map_1.png shrunk to JPEGs, as byte arrays

Both headers are plain data with no collector logic, so later firmware (e.g.
navigation) can copy them as-is. Rerun after adding locations or editing maps:
    python3 07_ESP32_Collector/make_assets.py
Needs Pillow (pip install pillow).
"""

import csv
import io
import json
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parents[1]
RAW = REPO / "02_Data" / "01_Wifi_Daytime"
MAPS = REPO / "02_Data" / "03_Map_Data"
LABEL_MAP = REPO / "02_Data" / "02_Processed_Wifi_Daytime" / "splits" / "label_map.json"
OUT = Path(__file__).resolve().parent / "esp32_collector"

MAP_SIZE = (1536, 1024)  # pixel space of Coordinates.csv
JPEG_WIDTH = 1024        # enough to read room numbers when zoomed on a phone
JPEG_QUALITY = 60


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_locations() -> list[dict]:
    labels = {v.strip() for v in json.loads(LABEL_MAP.read_text()).values()}
    coords = {r["Label"].strip(): r for r in csv.DictReader(open(MAPS / "Coordinates.csv"))}

    locations = []
    for path in sorted(RAW.glob("*.csv")):
        with open(path, encoding="utf-8-sig") as f:
            label = next(csv.DictReader(f))["Location Label"].strip()
        if label not in labels or label not in coords:
            raise SystemExit(f"{path.name}: label {label!r} is missing from label_map.json or Coordinates.csv")
        c = coords[label]
        locations.append({
            "id": int(path.name.split("_")[0]),
            "label": label,
            "file": path.stem,
            "floor": int(c["MAP"]),
            "x": int(c["x"]),
            "y": int(c["y"]),
        })
    return locations


def write_locations(locations: list[dict]) -> None:
    rows = "\n".join(
        f'  {{{l["id"]:2d}, {l["floor"]}, {l["x"]:4d}, {l["y"]:4d}, {c_string(l["label"])}, {c_string(l["file"])}}},'
        for l in locations
    )
    (OUT / "locations.h").write_text(f"""#pragma once
// GENERATED by make_assets.py from 02_Data/. Do not edit by hand.

#include <stdint.h>

struct KnownLocation {{
  uint8_t id;         // number prefix of the phone CSV in 02_Data/01_Wifi_Daytime
  uint8_t floor;      // 0 = ground floor, 1 = first floor
  uint16_t x, y;      // pixel on map_<floor> (MAP_WIDTH x MAP_HEIGHT)
  const char *label;  // canonical label from label_map.json
  const char *file;   // phone CSV name: a longer description of the spot
}};

static const int MAP_WIDTH = {MAP_SIZE[0]};
static const int MAP_HEIGHT = {MAP_SIZE[1]};

static const KnownLocation LOCATIONS[] = {{
{rows}
}};
static const int LOCATION_COUNT = sizeof(LOCATIONS) / sizeof(LOCATIONS[0]);
""")


def jpeg_bytes(png: Path) -> bytes:
    image = Image.open(png)
    flat = Image.new("RGB", image.size, "white")
    flat.paste(image, mask=image.convert("RGBA").split()[3])
    height = round(JPEG_WIDTH * image.height / image.width)
    out = io.BytesIO()
    flat.resize((JPEG_WIDTH, height), Image.LANCZOS).save(out, "JPEG", quality=JPEG_QUALITY, optimize=True)
    return out.getvalue()


def write_maps() -> None:
    parts = ["#pragma once\n// GENERATED by make_assets.py from 02_Data/03_Map_Data. Do not edit by hand.\n",
             "#include <Arduino.h>\n"]
    for floor in (0, 1):
        data = jpeg_bytes(MAPS / f"map_{floor}.png")
        lines = ",\n".join(
            "  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)
        )
        parts.append(f"static const uint8_t MAP_{floor}_JPG[] PROGMEM = {{\n{lines}\n}};\n")
        parts.append(f"static const size_t MAP_{floor}_JPG_LEN = sizeof(MAP_{floor}_JPG);\n")
        print(f"map_{floor}.jpg: {len(data) / 1024:.0f} KB")
    (OUT / "floor_maps.h").write_text("\n".join(parts))


if __name__ == "__main__":
    locations = load_locations()
    write_locations(locations)
    print(f"locations.h: {len(locations)} locations")
    write_maps()
